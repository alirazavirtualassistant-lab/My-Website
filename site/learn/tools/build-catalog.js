#!/usr/bin/env node
/* Generates assets/js/catalog.js, data/search-index.json and data/interview-bank.json from courses/*.md.
   Run after adding or editing any course:  node tools/build-catalog.js  */
const fs = require('fs'), path = require('path');
const MD = require('../assets/js/md.js');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'courses');

const TRACKS = ['Programming', 'Document Engineering', 'Data & Reporting', 'Office & Tools', 'AI & Automation', 'Computer Science', 'Operations & Career'];
// preferred display order inside each track (anything missing goes after, alphabetically)
const ORDER = ['python', 'javascript', 'html', 'css', 'sql', 'nodejs', 'oop', 'git-devtools',
  'python-docx', 'docx-js', 'ooxml', 'openpyxl', 'reportlab', 'weasyprint', 'pymupdf', 'pikepdf', 'pdfplumber', 'pptxgenjs', 'pdf-forms', 'epub3', 'prepress', 'libreoffice-automation',
  'excel', 'powerbi', 'pandas', 'data-cleaning-reporting', 'spss-eviews',
  'word-expert', 'powerpoint-expert', 'workspace-tools', 'design-tools', 'citations',
  'llm-api', 'dsa', 'databases', 'sdlc', 'networks', 'leadership-qa', 'title-insurance', 'interview-mastery'];

function plain(md) {
  return String(md).replace(/```[\s\S]*?```/g, ' ').replace(/<[^>]+>/g, ' ').replace(/[#>*_`|\-]+/g, ' ').replace(/\s+/g, ' ').trim();
}

const courses = [], index = [], bank = [];
fs.readdirSync(dir).filter(f => f.endsWith('.md') && !f.startsWith('_')).forEach(f => {
  const id = f.replace(/\.md$/, '');
  const c = MD.parseCourse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const m = c.meta;
  courses.push({
    id, title: m.title || id, icon: m.icon || '📘', track: m.track || 'Programming', color: m.color || '#04aa6d', runner: m.runner || 'none',
    tagline: m.tagline || '', description: m.description || '', chapters: c.chapters.length,
    levels: c.levels.map(l => ({ name: l.name, count: l.chapters.length })),
    words: c.chapters.reduce((a, ch) => a + ch.words, 0), quiz: c.chapters.reduce((a, ch) => a + ch.quiz.length, 0), interview: c.chapters.reduce((a, ch) => a + ch.interview.length, 0)
  });
  c.chapters.forEach(ch => {
    index.push({ cid: id, course: m.title || id, icon: m.icon || '', level: ch.level, id: ch.id, title: ch.title, text: plain(ch.body).slice(0, 600) });
    ch.interview.forEach(iq => bank.push({ cid: id, course: m.title || id, icon: m.icon || '', track: m.track || '', level: ch.level, chid: ch.id, chapter: ch.title, q: iq.q, a: iq.a }));
  });
});
courses.sort((a, b) => {
  const ta = TRACKS.indexOf(a.track), tb = TRACKS.indexOf(b.track);
  if (ta !== tb) return ta - tb;
  const oa = ORDER.indexOf(a.id), ob = ORDER.indexOf(b.id);
  if (oa !== -1 && ob !== -1) return oa - ob;
  if (oa !== -1) return -1; if (ob !== -1) return 1;
  return a.title.localeCompare(b.title);
});

const catalog = { generated: new Date().toISOString(), tracks: TRACKS, courses };
fs.mkdirSync(path.join(root, 'data'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets', 'js', 'catalog.js'), '/* generated by tools/build-catalog.js — do not edit by hand */\nwindow.CATALOG = ' + JSON.stringify(catalog, null, 1) + ';\n');
fs.writeFileSync(path.join(root, 'data', 'search-index.json'), JSON.stringify(index));
fs.writeFileSync(path.join(root, 'data', 'interview-bank.json'), JSON.stringify(bank));
console.log(`catalog: ${courses.length} courses, ${index.length} chapters, ${bank.length} interview questions`);
