#!/usr/bin/env node
/* Build a fully self-contained OFFLINE copy of SkillForge that works by double-clicking
   index.html (file://) with no web server. It inlines every course, the search index and
   the interview bank into one JS file, injects it into each HTML page, and writes the
   result to ../../../dist-offline/skillforge/ .   Usage: node tools/build-offline.js       */
const fs = require('fs'), path = require('path');
const MD = require('../assets/js/md.js');
const root = path.join(__dirname, '..');                 // site/learn
const out = path.join(root, '..', '..', 'dist-offline', 'skillforge');

function rmrf(p) { if (fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true }); }
function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

rmrf(path.join(root, '..', '..', 'dist-offline'));
fs.mkdirSync(out, { recursive: true });

// Copy the app shell. We do NOT copy courses/*.md or the generated JSON — inline-content.js
// carries all of that, which keeps the offline download roughly half the size.
for (const item of ['assets', 'index.html', 'course.html', 'tryit.html', 'practice.html', 'interview.html', 'roadmap.html', 'README.md']) {
  const s = path.join(root, item);
  if (!fs.existsSync(s)) continue;
  const d = path.join(out, item);
  if (fs.statSync(s).isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
}
// data/ holds only the JS data the pages load (challenges.js, behavioral.js) plus inline-content.js below.
fs.mkdirSync(path.join(out, 'data'), { recursive: true });
for (const f of ['challenges.js', 'behavioral.js']) fs.copyFileSync(path.join(root, 'data', f), path.join(out, 'data', f));

// Build the inline content bundle from source.
const courses = {}, index = [], bank = [];
function plain(md) { return String(md).replace(/```[\s\S]*?```/g, ' ').replace(/<[^>]+>/g, ' ').replace(/[#>*_`|\-]+/g, ' ').replace(/\s+/g, ' ').trim(); }
fs.readdirSync(path.join(root, 'courses')).filter(f => f.endsWith('.md') && !f.startsWith('_')).sort().forEach(f => {
  const id = f.replace(/\.md$/, '');
  const text = fs.readFileSync(path.join(root, 'courses', f), 'utf8');
  courses[id] = text;
  const c = MD.parseCourse(text), m = c.meta;
  c.chapters.forEach(ch => {
    index.push({ cid: id, course: m.title || id, icon: m.icon || '', level: ch.level, id: ch.id, title: ch.title, text: plain(ch.body).slice(0, 600) });
    ch.interview.forEach(iq => bank.push({ cid: id, course: m.title || id, icon: m.icon || '', track: m.track || '', level: ch.level, chid: ch.id, chapter: ch.title, q: iq.q, a: iq.a }));
  });
});
const inline = '/* SkillForge offline bundle — all lesson content inlined so the site works from file:// with no server. Generated by tools/build-offline.js */\n'
  + 'window.COURSES = ' + JSON.stringify(courses) + ';\n'
  + 'window.SEARCH_INDEX = ' + JSON.stringify(index) + ';\n'
  + 'window.INTERVIEW_BANK = ' + JSON.stringify(bank) + ';\n';
fs.writeFileSync(path.join(out, 'data', 'inline-content.js'), inline);

// Inject the inline bundle into every HTML page (before app.js so globals exist first).
for (const html of ['index.html', 'course.html', 'tryit.html', 'practice.html', 'interview.html', 'roadmap.html']) {
  const p = path.join(out, html);
  let s = fs.readFileSync(p, 'utf8');
  if (s.indexOf('data/inline-content.js') === -1) {
    s = s.replace('<script src="assets/js/app.js"></script>',
      '<script src="data/inline-content.js"></script>\n<script src="assets/js/app.js"></script>');
  }
  fs.writeFileSync(p, s);
}

// An offline landing note.
fs.writeFileSync(path.join(out, 'OPEN-ME.txt'),
  'SkillForge — offline learning site\n' +
  '==================================\n\n' +
  'Just open  index.html  in any web browser (double-click it).\n' +
  'No internet or server is needed to read lessons, take quizzes, do exercises,\n' +
  'or use the interview prep, flashcards, mock interview and roadmap.\n\n' +
  'Only these need internet (they load a runtime from the web the first time):\n' +
  '  - "Try it Yourself" for Python and SQL\n' +
  '  - Generating real Word/PowerPoint/PDF files in the JavaScript editor\n' +
  'Everything else, including all reading and all HTML/CSS/JS examples, works offline.\n\n' +
  'Tip: bookmark index.html, or add it to your phone home screen, for one-tap access.\n');

const files = [];
(function walk(d, base) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const rel = base ? base + '/' + e.name : e.name; if (e.isDirectory()) walk(path.join(d, e.name), rel); else files.push(rel); } })(out, '');
console.log('Offline build written to ' + out);
console.log('  ' + Object.keys(courses).length + ' courses inlined, ' + files.length + ' files total');
console.log('  inline-content.js: ' + (fs.statSync(path.join(out, 'data', 'inline-content.js')).size / 1024 / 1024).toFixed(1) + ' MB');
